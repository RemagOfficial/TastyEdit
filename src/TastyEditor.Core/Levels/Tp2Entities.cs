    private static readonly System.Collections.Generic.HashSet<string> NameSet =
        new(System.StringComparer.Ordinal);

    static Tp2Entities()
    {
        foreach (var d in All) NameSet.Add(d.Name);
    }

    /// <summary>True when name is a known entity (has an entity definition).</summary>
    public static bool IsEntity(string? name) =>
        !string.IsNullOrWhiteSpace(name) && NameSet.Contains(name);

    /// <summary>Display label for an entity name (falls back to the name when unknown).</summary>
    public static string DisplayOf(string? name)
    {
        if (string.IsNullOrEmpty(name)) return "";
        var d = System.Array.Find(All, x => x.Name == name);
        return string.IsNullOrEmpty(d.Name) ? name! : d.Display;
    }
